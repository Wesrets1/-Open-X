/* ============================================================
   crowd.js — background personas

   A timeline with eight people looks staged; real feeds are noisy.
   This module maintains a pool of lightweight "crowd" accounts that
   exist only to make a post feel like it landed in public.

   Design constraints:

     • Crowd accounts are NOT agents. They have no mood, patience,
       grudge or memory loops, so they cost nothing per tick and
       never compete with the cast for relevance.

     • They only ever react to posts that already exist. They never
       initiate, never DM, never appear in Messages.

     • Their handles and nicknames are generated by the model once
       per world, then stored. Regeneration is explicit, not passive.

     • Everything is seeded and bounded so a save stays small.
   ============================================================ */

import { getState, upsertNpc, addLog } from './db.js';
import { chatJSON } from './llm.js';
import { getConfig } from './config.js';
import { rng, uid, clamp, slug } from './util.js';
import { dbg, warn } from './debug.js';

/** How many crowd accounts a world carries. */
export const CROWD_SIZE = 14;

/** Hard ceiling — never let a world balloon. */
const CROWD_MAX = 28;

/** Fallback handles/nicknames when the model is unavailable. */
const LOCAL_NICKS = [
  'moth', 'glass', 'damp', 'orbit', 'velvet', 'tangent', 'static', 'crumb',
  'hollow', 'pixel', 'haze', 'sable', 'ninth', 'copper', 'lichen', 'brine',
  'ember', 'quill', 'drift', 'moss', 'vapor', 'linen', 'rust', 'chime',
];

const LOCAL_SUFFIX = ['_', '.', '__', 'irl', 'core', 'posting', 'hours', 'adjacent', 'daily', 'txt'];

const LOCAL_ARCHETYPES = ['lurker', 'stan', 'chaos', 'critic', 'wholesome', 'influencer'];

/**
 * Local nickname generator — used in demo mode, when the endpoint
 * fails, or to top a short model response back up.
 */
export function localNickname(exists = new Set()) {
  for (let attempt = 0; attempt < 40; attempt++) {
    const base = rng.pick(LOCAL_NICKS);
    const roll = Math.random();
    const handle = roll < 0.45
      ? `${base}${rng.pick(['', String(rng.int(1, 99))])}`
      : roll < 0.8
        ? `${base}${rng.pick(LOCAL_SUFFIX)}`
        : `${rng.pick(LOCAL_NICKS)}${rng.pick(LOCAL_NICKS)}`.slice(0, 14);
    const clean = slug(handle).slice(0, 18) || 'anon';
    if (exists.has(clean)) continue;
    return { handle: clean, name: displayFromHandle(clean) };
  }
  const fallback = `anon${Date.now().toString(36).slice(-4)}`;
  return { handle: fallback, name: displayFromHandle(fallback) };
}

/** "dampcore" → "dampcore", "moth_irl" → "moth irl" — keep it lowercase-odd. */
function displayFromHandle(h) {
  return String(h).replace(/_/g, ' ').slice(0, 24);
}

/* ============================================================
   Model-backed generation
   ============================================================ */

const CROWD_SYSTEM = `You invent throwaway social-media accounts for a life simulator.

These are background noise: the people who reply "lmaooo" and "who asked" under a post,
never the main cast. They must NOT be memorable protagonists.

Rules:
- Handles are lowercase, short, and feel real: not_firstname_lastname.
  Good: dampcore, moth_irl, 3amsnacc, nottheo, glasshours
  Bad: JohnSmith92, cooluser123, xxx_gamer_xxx
- Display names are lowercase and weird, often just the handle respaced.
- Give each one a one-line bio that hints at a specific ordinary life.
- Set verified to false for every single one.
- Archetypes must be drawn from the provided list.
- Vary wildly. No two should feel like they belong to the same person.`;

/**
 * Ask the endpoint for a batch of crowd accounts.
 * Falls back to local generation on any failure.
 */
export async function generateCrowd(count = CROWD_SIZE, context = {}) {
  const cfg = getConfig();
  const want = clamp(count, 1, CROWD_MAX);
  const existing = new Set(getState().npcs.map((n) => n.handle.replace(/^@/, '').toLowerCase()));

  if (cfg.demoMode) {
    return buildLocalCrowd(want, existing);
  }

  const theme = context.theme || getState().meta?.theme || 'modern';
  const premise = context.premise || getState().meta?.premise || '';

  try {
    const json = await chatJSON({
      messages: [
        { role: 'system', content: CROWD_SYSTEM },
        {
          role: 'user',
          content: [
            `World theme: ${theme}`,
            premise ? `World premise: ${premise}` : '',
            `Existing handles already in use: ${[...existing].join(', ') || 'none'}`,
            '',
            `Write ${want} background accounts as JSON:`,
            '{ "accounts": [ { "name": "...", "handle": "...", "bio": "...", "archetype": "..." } ] }',
            `Allowed archetypes: ${LOCAL_ARCHETYPES.join(', ')}`,
          ].filter(Boolean).join('\n'),
        },
      ],
      tier: 'cheap',
      maxTokens: 900,
      temperature: 1.0,
      schema: true,
    });

    const list = Array.isArray(json?.accounts) ? json.accounts
      : Array.isArray(json) ? json
        : [];

    const built = [];
    for (const a of list) {
      const nick = normaliseAccount(a, existing);
      if (!nick) continue;
      built.push(nick);
      existing.add(nick.handle);
    }

    // Model returned too few — top up locally so the crowd is never thin.
    while (built.length < want) {
      const n = localNickname(existing);
      existing.add(n.handle);
      built.push({ ...n, bio: 'here.', archetype: rng.pick(LOCAL_ARCHETYPES) });
    }

    dbg('crowd:generated', { want, got: built.length, model: true });
    return built.slice(0, want);
  } catch (e) {
    warn('crowd generation fell back to local', e);
    return buildLocalCrowd(want, existing);
  }
}

function normaliseAccount(a, existing) {
  if (!a) return null;
  const rawHandle = String(a.handle || '').trim();
  let handle = slug(rawHandle).slice(0, 18);
  if (!handle) {
    const n = localNickname(existing);
    handle = n.handle;
  }
  // Dedupe against everything already in the world.
  let unique = handle;
  let n = 2;
  while (existing.has(unique)) unique = `${handle}${n++}`.slice(0, 20);

  const archetype = LOCAL_ARCHETYPES.includes(a.archetype) ? a.archetype : rng.pick(LOCAL_ARCHETYPES);

  return {
    handle: unique,
    name: String(a.name || displayFromHandle(unique)).trim().slice(0, 24).toLowerCase() || displayFromHandle(unique),
    bio: String(a.bio || '').trim().slice(0, 90) || 'here.',
    archetype,
  };
}

function buildLocalCrowd(count, existing) {
  const out = [];
  for (let i = 0; i < count; i++) {
    const n = localNickname(existing);
    existing.add(n.handle);
    out.push({
      ...n,
      bio: rng.pick([
        'here.', 'mostly lurking.', 'i reply to everything.', 'no thoughts',
        'chronically online.', '3am poster.', 'just reading.', 'hi.',
      ]),
      archetype: rng.pick(LOCAL_ARCHETYPES),
    });
  }
  dbg('crowd:generated', { count: out.length, model: false });
  return out;
}

/* ============================================================
   Install into a world
   ============================================================ */

function crowdNpc(account) {
  return {
    id: uid('npc'),
    name: account.name,
    handle: '@' + account.handle,
    archetype: account.archetype || 'lurker',
    vibe: '',
    bio: account.bio || 'here.',
    followers: rng.int(12, 900),
    verified: false,
    affinity: 0,
    posts: 0,
    lastActive: Date.now() - rng.int(0, 3_600_000),
    isNew: false,
    crowd: true,
  };
}

/** Add accounts to the active world. Skips duplicates. */
export function installCrowd(accounts = []) {
  const s = getState();
  const have = new Set(s.npcs.map((n) => n.handle.toLowerCase()));
  let added = 0;
  for (const a of accounts) {
    const handle = '@' + String(a.handle || '').toLowerCase();
    if (!a.handle || have.has(handle)) continue;
    have.add(handle);
    upsertNpc(crowdNpc(a));
    added++;
  }
  if (added) dbg('crowd:installed', { added });
  return added;
}

/** Every crowd account in the world. */
export function crowdMembers() {
  return getState().npcs.filter((n) => n.crowd === true);
}

/** The named cast — everyone who is not crowd. */
export function coreCast() {
  return getState().npcs.filter((n) => n.crowd !== true);
}

/** Top the crowd back up to a target size. */
export async function topUpCrowd(target = CROWD_SIZE) {
  const have = crowdMembers().length;
  if (have >= target) return 0;
  const accounts = await generateCrowd(Math.min(target - have, CROWD_MAX - have));
  return installCrowd(accounts);
}

/** Remove every crowd account. */
export function clearCrowd() {
  const s = getState();
  const before = s.npcs.length;
  s.npcs = s.npcs.filter((n) => n.crowd !== true);
  return before - s.npcs.length;
}

/** Count for the settings panel. */
export function crowdStats() {
  const all = getState().npcs;
  return {
    crowd: all.filter((n) => n.crowd).length,
    cast: all.filter((n) => !n.crowd).length,
    target: CROWD_SIZE,
  };
}

