/** Reply lines that read like real background noise. */
const LOCAL_REPLIES = [
  'who asked', 'lmaooo', 'this is so real', 'first', 'no way',
  'ok but why is this me', 'screaming', 'the way i ran here',
  'not me seeing this at 3am', 'unhinged behaviour', 'i needed this',
  'wait what happened', 'delete this', 'genuinely obsessed',
  'this aged well', 'ratio', 'crying', 'the lore thickens',
  'someone check on them', 'respectfully, no', 'ok and?',
  'this is the content i signed up for', 'saving this',
  'see this is why i follow you', 'and nobody clapped',
  'bestie what', 'i have questions', 'this is a lot to process',
  'finally something worth reading', 'who hurt you',
  'nah this is wild', 'i felt that', 'actual poetry',
];

const LOCAL_REACTIONS = ['lmaooo', 'same', 'who asked', 'real', 'this', 'dead', 'hmm'];

/**
 * Attach a handful of crowd replies to a post.
 *
 * @param {string} postId
 * @param {object} [opts]
 * @param {number} [opts.min]
 * @param {number} [opts.max]
 * @returns {number} how many replies were added
 */
export function crowdReply(postId, { min = 1, max = 5 } = {}) {
  const s = getState();
  const post = s.posts.find((p) => p.id === postId);
  if (!post) return 0;

  const pool = crowdMembers();
  if (!pool.length) return 0;

  const count = rng.int(min, max);
  const chosen = new Set();
  let added = 0;

  for (let i = 0; i < count; i++) {
    // Pick a crowd member who hasn't already replied here.
    let npc = null;
    for (let attempt = 0; attempt < 8; attempt++) {
      const candidate = rng.pick(pool);
      if (chosen.has(candidate.id)) continue;
      if ((post.replies || []).some((r) => r.authorId === candidate.id)) continue;
      npc = candidate;
      break;
    }
    if (!npc) break;
    chosen.add(npc.id);

    post.replies = post.replies || [];
    post.replies.push({
      id: uid('rep'),
      authorId: npc.id,
      authorName: npc.name,
      authorHandle: npc.handle,
      text: rng.pick(LOCAL_REPLIES),
      ts: Date.now() - rng.int(0, 90_000),
      crowd: true,
    });
    added++;
  }

  if (post.replies && post.replies.length > 40) post.replies.length = 40;
  if (added) dbg('crowd:replied', { post: postId, added });
  return added;
}

/** Pad a post's engagement numbers so the feed doesn't look dead. */
export function crowdEngagement(postId, { looks = true } = {}) {
  const s = getState();
  const post = s.posts.find((p) => p.id === postId);
  if (!post) return;
  if (looks) {
    post.likes = (post.likes || 0) + rng.int(3, 140);
    post.reposts = (post.reposts || 0) + rng.int(0, 12);
  }
}
